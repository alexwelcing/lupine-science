#!/usr/bin/env node
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(PROJECT, '../../..');
const TEMPLATE = path.join(PROJECT, 'index.html');
const OUTPUT = path.join(PROJECT, 'deck.html');
const EVIDENCE = path.join(PROJECT, 'evidence-manifest.json');
const ASSET_LOCK = path.join(PROJECT, 'asset-lock.json');

function sha256(buffer) {
  return crypto.createHash('sha256').update(buffer).digest('hex');
}

function dataUrl(file, mime) {
  return `data:${mime};base64,${fs.readFileSync(file).toString('base64')}`;
}

let html = fs.readFileSync(TEMPLATE, 'utf8');
const evidenceText = fs.readFileSync(EVIDENCE, 'utf8').trim().replace(/<\//g, '<\\/');
const lock = JSON.parse(fs.readFileSync(ASSET_LOCK, 'utf8'));

if (!html.includes('__EVIDENCE_MANIFEST__')) {
  throw new Error('index.html is missing the evidence-manifest marker');
}
html = html.replace('__EVIDENCE_MANIFEST__', evidenceText);

const fonts = new Map([
  ['/fonts/newsreader-var.woff2', path.join(ROOT, 'public/fonts/newsreader-var.woff2')],
  ['/fonts/plex-mono-400.woff2', path.join(ROOT, 'public/fonts/plex-mono-400.woff2')],
  ['/fonts/plex-mono-600.woff2', path.join(ROOT, 'public/fonts/plex-mono-600.woff2')],
]);
for (const [url, file] of fonts) {
  if (!fs.existsSync(file)) throw new Error(`missing font: ${path.relative(ROOT, file)}`);
  html = html.replaceAll(`url("${url}")`, `url("${dataUrl(file, 'font/woff2')}")`);
}

for (const asset of lock.assets) {
  const file = path.join(ROOT, asset.path);
  if (!fs.existsSync(file)) throw new Error(`missing certified asset: ${asset.path}`);
  const bytes = fs.readFileSync(file);
  const digest = sha256(bytes);
  if (digest !== asset.sha256) throw new Error(`certified asset hash mismatch: ${asset.path}`);
  const source = `src="/${asset.path.replace(/^public\//, '')}"`;
  if (!html.includes(source)) throw new Error(`template does not reference certified asset: ${asset.path}`);
  html = html.replace(source, `src="data:image/png;base64,${bytes.toString('base64')}" data-certified-asset="${asset.asset_id}" data-asset-sha256="${asset.sha256}"`);
}

html = html.replace('<a href="/venture/lupine-science-venture-deck.pdf" download>PDF</a>', '');
html = html.replace(
  '<meta name="description" content="Lupine Science venture deck: an evidence-locked makeability layer for materials discovery.">',
  '<meta name="description" content="Lupine Science venture deck: a self-contained, evidence-locked makeability layer for materials discovery.">\n  <meta name="offline-artifact" content="self-contained">',
);
html = html.replace('</body>', `  <!-- Standalone build: all fonts, certified images, CSS, JavaScript, and evidence are embedded. SHA-256: generated by build-standalone.mjs. -->\n</body>`);

fs.writeFileSync(OUTPUT, html);
console.log(`standalone venture deck: ${path.relative(ROOT, OUTPUT)}`);
console.log(`slides: ${(html.match(/<section class="slide(?: is-active)?"/g) || []).length}`);
console.log(`bytes: ${fs.statSync(OUTPUT).size}`);
console.log(`sha256: ${sha256(fs.readFileSync(OUTPUT))}`);
