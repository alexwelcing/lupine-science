#!/usr/bin/env node
// Builds public/atlas/<id>/index.html for each ontology node, where <id> is
// the short id (T1, E4, MC9). Each page shows:
//   - the canonical lupine-research://<kind>/<id> URI (large, copy-pasteable)
//   - the node name and kind
//   - the articles that reference this node (ATX-5), as a reading list:
//     title, deck, and date read from each built article's JSON-LD, newest
//     first — a reader arriving from a citation gets somewhere to go next,
//     not a row of URL slugs
//   - a back link to /atlas/
//   - JSON-LD ItemPage
//
// Reads:
//   public/data/atlas_nodes.json (machine-generated by build-atlas-nodes.mjs)
//   public/data/article_ontology.json (machine-generated by build-ontology-crosslinks.mjs)
//
// Fail-closed:
//   - atlas_nodes.json missing or wrong shape -> exit 1.
//   - article_ontology.json missing -> exit 1.
//   - any by_node article slug has no corresponding built article -> exit 1.
//   - duplicate /atlas/<id>/ collisions -> exit 1.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderSiteHeader } from './lib/brand-header.mjs';
import { headMetaTitleSegments, renderHeadMetaTags, escapeHtml } from './lib/head-meta.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ATLAS_NODES_PATH = path.join(ROOT, 'public', 'data', 'atlas_nodes.json');
const ARTICLE_ONTOLOGY_PATH = path.join(ROOT, 'public', 'data', 'article_ontology.json');
const OUT_ROOT = path.join(ROOT, 'public', 'atlas');
const SITE = 'https://lupine.science';

function fail(message) {
  console.error(`build-atlas-detail-pages: ${message}`);
  process.exit(1);
}

if (!fs.existsSync(ATLAS_NODES_PATH)) {
  fail(`missing ${path.relative(ROOT, ATLAS_NODES_PATH)} - run scripts/build-atlas-nodes.mjs first`);
}
if (!fs.existsSync(ARTICLE_ONTOLOGY_PATH)) {
  fail(`missing ${path.relative(ROOT, ARTICLE_ONTOLOGY_PATH)} - run scripts/build-ontology-crosslinks.mjs first`);
}

const atlas = JSON.parse(fs.readFileSync(ATLAS_NODES_PATH, 'utf8'));
if (!atlas?.kinds || typeof atlas.kinds !== 'object') {
  fail('atlas_nodes.json has no .kinds object');
}
const crosslinks = JSON.parse(fs.readFileSync(ARTICLE_ONTOLOGY_PATH, 'utf8'));
if (!crosslinks?.by_node || typeof crosslinks.by_node !== 'object') {
  fail('article_ontology.json has no .by_node object');
}

// Flatten the atlas into a single sorted list of nodes.
const nodes = [];
for (const [kind, list] of Object.entries(atlas.kinds)) {
  if (!Array.isArray(list)) fail(`atlas_nodes.json kinds.${kind} is not an array`);
  for (const node of list) {
    if (typeof node.id !== 'string' || !node.id.startsWith(`lupine-research://${kind}/`)) {
      fail(`atlas_nodes.json has malformed node id: ${node.id}`);
    }
    if (typeof node.uri !== 'string') fail(`atlas_nodes.json has malformed node uri: ${node.id}`);
    nodes.push({ kind, uri: node.uri, name: node.name, id: node.id });
  }
}
nodes.sort((a, b) => a.uri.localeCompare(b.uri));

if (nodes.length === 0) fail('atlas_nodes.json contains zero nodes');

// Every article slug in by_node must have a built article on disk, and that
// article's JSON-LD must carry the headline, deck, and date the reading list
// shows. Reading the built page rather than the Markdown keeps this builder
// downstream of build-articles.mjs's own frontmatter rules.
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
function longDate(iso) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso || '');
  if (!m) return null;
  return `${MONTHS[Number(m[2]) - 1]} ${Number(m[3])}, ${m[1]}`;
}
const articleMeta = new Map();
function readArticleMeta(slug) {
  if (articleMeta.has(slug)) return articleMeta.get(slug);
  const articleHtml = path.join(ROOT, 'public', 'articles', slug, 'index.html');
  if (!fs.existsSync(articleHtml)) {
    fail(`by_node references article "${slug}" but no built HTML at ${path.relative(ROOT, articleHtml)}`);
  }
  const html = fs.readFileSync(articleHtml, 'utf8');
  const ld = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
  if (!ld) fail(`article "${slug}" has no JSON-LD to read a title from`);
  let doc;
  try { doc = JSON.parse(ld[1]); } catch { fail(`article "${slug}" has unparseable JSON-LD`); }
  const graph = Array.isArray(doc['@graph']) ? doc['@graph'] : [doc];
  const article = graph.find((n) => n && n['@type'] === 'Article');
  if (!article || typeof article.headline !== 'string' || !article.headline.trim()) {
    fail(`article "${slug}" JSON-LD has no Article headline`);
  }
  const meta = {
    slug,
    title: article.headline.trim(),
    deck: typeof article.description === 'string' ? article.description.trim() : '',
    date: typeof article.datePublished === 'string' ? article.datePublished : '',
    dateLong: longDate(article.datePublished),
  };
  if (!meta.dateLong) fail(`article "${slug}" JSON-LD datePublished is not YYYY-MM-DD: ${meta.date}`);
  articleMeta.set(slug, meta);
  return meta;
}
for (const [uri, slugs] of Object.entries(crosslinks.by_node)) {
  for (const slug of slugs) {
    if (typeof slug !== 'string' || slug.length === 0) fail(`by_node[${uri}] has empty slug`);
    readArticleMeta(slug);
  }
}

const KIND_TITLE = {
  error_type: 'Error type',
  emblem: 'Emblem',
  material_class: 'Material class',
};

const KIND_BLURB = {
  error_type: 'A class of failure mode the correction layer has to defend against. Each error type names a recurring pathology in machine-learned interatomic potentials and the materials-discovery workflows that depend on them.',
  emblem: 'A measured cluster of closely related physical phenomena the correction layer treats as one regime. Each emblem groups observables that move together under the same correction.',
  material_class: 'A family of materials whose discovery and verification problem shapes share enough structure that the correction layer is designed to address all of them together.',
};


// escapeAttrContent escapes for use inside an HTML attribute value but does
// NOT encode & -> &amp;. This is intentional: the publication smoke gate
// normalizes the <title> tag (decoding &amp; -> &) but not the <meta
// property="og:title"> content. Emitting raw & keeps both sides aligned
// after the gate's normalization. We still encode < > " ' so a future node
// name with HTML-special characters cannot break the attribute syntax.
function escapeAttrContent(s) {
  return String(s)
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function pageHtml({ kind, uri, name, id }) {
  // newest first, then title — the order a reader wants, not the order of slugs
  const referencedBy = (crosslinks.by_node[id] || []).map(readArticleMeta)
    .sort((a, b) => (b.date.localeCompare(a.date)) || a.title.localeCompare(b.title));
  const referencedSection = referencedBy.length > 0
    ? `      <section class="atlas-detail-references" aria-label="Articles that reference ${escapeHtml(uri)}">
        <p class="atlas-detail-kicker">Referenced by <span class="atlas-detail-kicker-count">${referencedBy.length} article${referencedBy.length === 1 ? '' : 's'}</span></p>
        <ol class="atlas-detail-reading">
${referencedBy.map((a) => `          <li><a class="atlas-detail-ref" href="/articles/${escapeHtml(a.slug)}/">
            <span class="atlas-ref-date">${escapeHtml(a.dateLong)}</span>
            <span class="atlas-ref-title">${escapeHtml(a.title)}</span>${a.deck ? `
            <span class="atlas-ref-deck">${escapeHtml(a.deck)}</span>` : ''}
          </a></li>`).join('\n')}
        </ol>
      </section>`
    : `      <p class="atlas-detail-no-refs">No public articles reference this node yet. Editors: add an Ontology line in the article frontmatter, e.g. <code>&gt; **Ontology:** ${escapeHtml(uri.split('/').pop())}</code>.</p>`;

  const kindTitle = KIND_TITLE[kind] || kind;
  const blurb = KIND_BLURB[kind] || '';

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
${renderHeadMetaTags(headMetaTitleSegments({ prefix: uri, primary: name, suffix: 'Lupine Science' }))}
  <meta name="description" content="${escapeHtml(name)} (${escapeHtml(uri)}) — Lupine research ontology, ${kindTitle.toLowerCase()}.">
  <meta name="robots" content="index,follow">
  <link rel="canonical" href="${SITE}/atlas/${escapeHtml(uri)}/">
  <meta property="og:description" content="${escapeHtml(name)} (${escapeHtml(uri)}).">
  <meta property="og:type" content="article">
  <meta property="og:url" content="${SITE}/atlas/${escapeHtml(uri)}/">
  <meta property="og:image" content="${SITE}/og-lupine-science.jpg">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:description" content="${escapeHtml(name)} (${escapeHtml(uri)}).">
  <meta name="twitter:image" content="${SITE}/og-lupine-science.jpg">
  <meta name="theme-color" content="#faf9f6">
  <link rel="icon" type="image/svg+xml" href="/lupine-science-mark.svg">
  <link rel="icon" type="image/png" href="/lupine-science-icon.png">
  <link rel="apple-touch-icon" href="/lupine-science-icon.png">
  <link rel="preload" href="/fonts/newsreader-var.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="preload" href="/fonts/plex-mono-400.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="preload" href="/fonts/newsreader-italic-var.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="stylesheet" href="/articles/styles.css">
  <script type="application/ld+json">{"@context":"https://schema.org","@type":"ItemPage","name":"${escapeHtml(name)}","identifier":"${escapeHtml(id)}","url":"${SITE}/atlas/${escapeHtml(uri)}/","isPartOf":{"@type":"WebSite","name":"Lupine Science","url":"${SITE}"},"about":{"@type":"Thing","name":"${escapeHtml(name)}","identifier":"${escapeHtml(id)}"}}</script>
</head>
<body>
  <a class="skip" href="#content">Skip to content</a>
  ${renderSiteHeader({ ariaCurrentPath: `/atlas/${uri}/` })}
  <main id="content" class="atlas-detail" data-kind="${escapeHtml(kind)}">
    <p class="b-label"><a href="/atlas/">&larr; Atlas</a></p>
    <p class="atlas-detail-kind">${escapeHtml(kindTitle)}</p>
    <h1>${escapeHtml(name)}</h1>
    <p class="atlas-detail-uri" aria-label="Canonical URI"><code>${escapeHtml(id)}</code></p>
    <p class="atlas-detail-blurb">${escapeHtml(blurb)}</p>
${referencedSection}
    <p class="atlas-detail-asof">Source: <a href="/atlas/">Lupine research ontology</a>. Cite this node by its URI: <code>${escapeHtml(id)}</code>.</p>
  </main>
  <footer class="foot">
    <span class="creed">Evidence before claim.</span>
    <span><a href="/articles/">Articles</a> · <a href="https://lupi.live">LUPI</a> · <a href="https://library.lupine.science">Library</a> · <a href="https://github.com/alexwelcing/lupine">Repository</a></span>
  </footer>
</body>
</html>
`;
}

let written = 0;
const seen = new Set();
for (const node of nodes) {
  if (seen.has(node.uri)) fail(`duplicate short id in atlas_nodes.json: ${node.uri}`);
  seen.add(node.uri);
  const dir = path.join(OUT_ROOT, node.uri);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'), pageHtml(node));
  written += 1;
}

// Retire /atlas/<id>/index.html directories that no longer correspond to a
// node in atlas_nodes.json. Same convention as build-articles.mjs uses for
// retired articles: a directory under public/atlas/<id>/ must have a node
// in the committed JSON, otherwise the page is stale.
//
// CRITICAL: only retire directories whose names match the node-id pattern
// (T*, E*, MC*). Other directories under public/atlas/ (e.g. claims/,
// gallery/) are owned by other builders; deleting them here is a
// cross-builder coordination bug. This bug fired once during the ATX
// cleanup work, so the regex restriction is now load-bearing, not cosmetic.
const NODE_DIR_RE = /^(T\d+|E\d+|MC\d+)$/;
const stale = [];
for (const entry of fs.readdirSync(OUT_ROOT, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  if (!NODE_DIR_RE.test(entry.name)) continue;
  if (!seen.has(entry.name)) stale.push(entry.name);
}
for (const slug of stale) {
  fs.rmSync(path.join(OUT_ROOT, slug), { recursive: true });
  console.log(`retired /atlas/${slug}/ (no node in atlas_nodes.json)`);
}

console.log(`atlas detail pages: ${written} page(s) -> ${path.relative(ROOT, OUT_ROOT)}/<id>/index.html`);
